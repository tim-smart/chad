. "$(dirname "$0")/common.sh"
say "J1: secret from stdin with the flag"
printf 'hunter2' | node chad.ts secret-set --secret-stdin; echo "exit=$?"
echo "expected sha256 prefix: $(printf 'hunter2' | sha256sum | cut -c1-12)"
say "J2: no terminal, no flag (stdin = /dev/null)"
node chad.ts secret-set < /dev/null; echo "exit=$?"
say "J3: no terminal, no flag (stdin = pipe with data)"
printf 'hunter2' | node chad.ts secret-set; echo "exit=$?"
say "J4: hidden prompt on a pty (script(1)); typed 'hunter2' + Enter after 2s"
(sleep 2; printf 'hunter2\r'; sleep 1) | script -qec "node chad.ts secret-set" /dev/null | cat -v; echo "exit=${PIPESTATUS[1]}"
say "J5: effect/cli alone (Flag.Redacted + withFallbackPrompt(Prompt.Hidden)), flag given"
node chad.ts secret-raw --token hunter2; echo "exit=$?"
say "J6: effect/cli alone, no flag, stdin = /dev/null (timeout 5s)"
timeout 5 node chad.ts secret-raw < /dev/null 2>&1 | cat -v | head -20; echo "exit=${PIPESTATUS[0]}"
say "J7: effect/cli alone, no flag, stdin = pipe with 'hunter2\\n' (timeout 5s)"
printf 'hunter2\n' | timeout 5 node chad.ts secret-raw 2>&1 | cat -v | head -20; echo "exit=${PIPESTATUS[1]}"
say "J8: effect/cli alone on a pty"
(sleep 2; printf 'hunter2\r'; sleep 1) | script -qec "node chad.ts secret-raw" /dev/null | cat -v; echo "exit=${PIPESTATUS[1]}"
